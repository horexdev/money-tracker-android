import java.math.BigInteger

internal object SystemExchangeRates {
    private val rateScale = BigInteger.valueOf(RATE_SCALE_E8)

    fun rateE8(baseCurrency: String, targetCurrency: String): Long {
        val baseRate = requireUsdQuoteE8(baseCurrency)
        val targetRate = requireUsdQuoteE8(targetCurrency)
        return BigInteger.valueOf(targetRate)
            .multiply(rateScale)
            .add(BigInteger.valueOf(baseRate).divide(BigInteger.valueOf(2)))
            .divide(BigInteger.valueOf(baseRate))
            .toLong()
            .takeIf { it > 0L }
            ?: RATE_SCALE_E8
    }

    fun hasUsdQuote(currencyCode: String): Boolean {
        return currencyCode in UsdQuoteRatesE8
    }

    private fun requireUsdQuoteE8(currencyCode: String): Long {
        return UsdQuoteRatesE8[currencyCode]
            ?: error("Missing built-in system exchange rate for $currencyCode")
    }

    private fun quoteFrom(
        currencyCode: String,
        multiplierNumerator: Long = 1L,
        multiplierDenominator: Long = 1L,
    ): Long {
        val baseQuote = CurrentUsdQuoteRatesE8[currencyCode]
            ?: error("Missing base quote for $currencyCode")
        return BigInteger.valueOf(baseQuote)
            .multiply(BigInteger.valueOf(multiplierNumerator))
            .add(BigInteger.valueOf(multiplierDenominator / 2L))
            .divide(BigInteger.valueOf(multiplierDenominator))
            .toLong()
            .takeIf { it > 0L }
            ?: error("Invalid derived quote for $currencyCode")
    }

